
const express = require('express');
const multer = require('multer');
const cors = require('cors');
const { execFile } = require('child_process');
const { promisify } = require('util');
const fs = require('fs/promises');
const os = require('os');
const path = require('path');

const app = express();
const execFileAsync = promisify(execFile);

// Allowed production and development origins
const allowedOrigins = new Set([
  'https://pdfconverterelite.xyz',
  'https://pdf-converter-elite.turaab321.workers.dev',
  'http://localhost:5173',
  'http://127.0.0.1:5173'
]);

// Add origins from Render environment variables
(process.env.FRONTEND_URL || '')
  .split(',')
  .map(value => value.trim())
  .filter(Boolean)
  .forEach(value => {
    try {
      allowedOrigins.add(new URL(value).origin);
    } catch {
      console.error('Invalid FRONTEND_URL:', value);
    }
  });

app.use(cors({
  origin(origin, callback) {
    if (!origin) return callback(null, true);

    let normalizedOrigin;

    try {
      normalizedOrigin = new URL(origin).origin;
    } catch {
      return callback(null, false);
    }

    if (
      allowedOrigins.has(normalizedOrigin) ||
      /^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(normalizedOrigin)
    ) {
      return callback(null, true);
    }

    console.error('Blocked CORS origin:', origin);
    return callback(null, false);
  },
  methods: ['GET', 'POST', 'OPTIONS'],
  allowedHeaders: ['Content-Type'],
  maxAge: 86400
}));

const upload = multer({
  storage: multer.memoryStorage(),
  limits: {
    fileSize: 20 * 1024 * 1024
  }
});

const sofficePath =
  process.env.LIBREOFFICE_PATH ||
  (process.platform === 'win32'
    ? 'C:\\Program Files\\LibreOffice\\program\\soffice.exe'
    : '/usr/bin/libreoffice');

// Health check
app.get('/api/health', (req, res) => {
  res.json({
    status: 'ok',
    service: 'PDF Converter Elite',
    libreoffice: process.env.LIBREOFFICE_PATH || sofficePath
  });
});

// Word to PDF conversion
app.post(
  '/api/word-to-pdf',
  upload.single('file'),
  async (req, res) => {
    let folder;

    try {
      if (!req.file) {
        return res.status(400).json({
          error: 'Please upload a Word document.'
        });
      }

      if (!/\.docx$/i.test(req.file.originalname)) {
        return res.status(400).json({
          error: 'Please upload a DOCX file.'
        });
      }

      folder = await fs.mkdtemp(
        path.join(os.tmpdir(), 'pdf-elite-')
      );

      const input = path.join(folder, 'document.docx');
      const output = path.join(folder, 'document.pdf');
      const profile = path.join(folder, 'profile');

      await fs.writeFile(input, req.file.buffer);

      // Correct Linux file URI for LibreOffice profile
      const profileURI = 'file://' + profile.replace(/\\/g, '/');

      const result = await execFileAsync(
        sofficePath,
        [
          '-env:UserInstallation=' + profileURI,
          '--headless',
          '--convert-to',
          'pdf',
          '--outdir',
          folder,
          input
        ],
        {
          timeout: 120000,
          windowsHide: true,
          maxBuffer: 10 * 1024 * 1024
        }
      );

      if (result.stderr) {
        console.log('LibreOffice:', result.stderr);
      }

      const pdf = await fs.readFile(output);

      if (pdf.subarray(0, 5).toString() !== '%PDF-') {
        throw new Error('Invalid PDF generated by LibreOffice.');
      }

      res.setHeader('Content-Type', 'application/pdf');
      res.setHeader(
        'Content-Disposition',
        'attachment; filename="converted.pdf"'
      );

      res.send(pdf);

    } catch (err) {
      console.error('WORD TO PDF ERROR:', err);

      if (!res.headersSent) {
        res.status(500).json({
          error: 'PDF conversion failed. ' +
            (process.env.NODE_ENV === 'production'
              ? 'Please try another DOCX document.'
              : err.message)
        });
      }

    } finally {
      if (folder) {
        await fs.rm(folder, {
          recursive: true,
          force: true
        }).catch(console.error);
      }
    }
  }
);

// Serve production website
const distPath = path.join(__dirname, 'dist');

app.use(express.static(distPath));

app.get(/^\/(?!api(?:\/|$)).*/, async (req, res) => {
  try {
    const pathname = decodeURIComponent(
      req.path.replace(/\/+$/, '') || '/'
    );

    const route = pathname === '/'
      ? path.join(distPath, 'index.html')
      : path.join(distPath, pathname, 'index.html');

    const htmlPath = await fs.stat(route)
      .then(stat => stat.isFile() ? route : null)
      .catch(() => null);

    if (htmlPath) {
      return res.sendFile(htmlPath);
    }

    res.status(404).send('Page not found');

  } catch (error) {
    res.status(400).send('Invalid URL');
  }
});

const PORT = Number(process.env.PORT) || 3001;
const HOST = '0.0.0.0';

app.listen(PORT, HOST, () => {
  console.log(
    `PDF Elite Backend running on http://${HOST}:${PORT}`
  );

  console.log('LibreOffice path:', sofficePath);
  console.log('Allowed origins:', [...allowedOrigins]);
});

